#!/usr/bin/env python3
"""Stages 3 + 4: build the Verilog-A coupling capacitor, assemble the FGFET
subcircuit (Fig. 1(c)) and calibrate C_VA against the memory-node transients
of Fig. 4 (Table II bias sequence).

Writes ../models/cva_cap.va, ../models/cva_cap.osdi (OpenVAF) and ../models/fgfet_subckt.sp.
Requires ../models/sfet_32nm.pm and ../models/vfet_32nm.pm (run fit_sfet.py / fit_vfet.py first).
"""
import os
import subprocess
import tempfile

import numpy as np
from scipy.optimize import least_squares

import spice

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
MODELS = os.path.join(ROOT, "models")
VA_OUT = os.path.join(MODELS, "cva_cap.va")
OSDI_OUT = os.path.join(MODELS, "cva_cap.osdi")
SUBCKT_OUT = os.path.join(MODELS, "fgfet_subckt.sp")

# Fig. 4 timing (us): initialize from 0, write from 1.1, storage from 2.2,
# read from 2.28 (read off the TCAD marker positions).
T_WRITE, T_STORE, T_READ, T_END = 1.1e-6, 2.2e-6, 2.28e-6, 2.40e-6
EDGE = 5e-9
# ngspice puts gmin (default 1e-12 S) across every BSIM4 junction, including the
# VFET source junction on the floating memory node: a 1 TOhm leak that drains
# ~0.1 V in 200 ns. Real leakage is many orders smaller. The default charge
# tolerance (chgtol = 1e-14 C) is also larger than the whole ~fC node charge.
SIM_OPTS = "gmin=1e-15 chgtol=1e-18"

# Memory-node targets read from Fig. 4 (TCAD markers): (time [s], V_MN [V], weight)
TARGETS = {
    0.05: [(0.012e-6, 0.60, 0.5), (0.56e-6, 0.00, 1.0), (1.09e-6, 0.00, 1.0),
           (1.66e-6, 0.05, 1.0), (2.19e-6, 0.05, 1.0),
           (2.25e-6, -1.70, 2.0), (2.34e-6, -0.58, 2.0)],
    1.0:  [(0.012e-6, 0.60, 0.5), (0.56e-6, 0.00, 1.0), (1.09e-6, 0.00, 1.0),
           (1.66e-6, 1.00, 1.0), (2.19e-6, 1.00, 1.0),
           (2.25e-6, -1.04, 2.0), (2.34e-6, 0.45, 2.0)],
}

# Initial guess from the replication guide; fitted values replace it.
CVA0 = dict(Cmax=0.85e-15, Cmin=0.35e-15, Vfb=-0.2, Vslp=0.45)
BOUNDS = dict(Cmax=(0.05e-15, 10e-15, True), Cmin=(0.05e-15, 10e-15, True),
              Vfb=(-3.0, 3.0, False), Vslp=(0.05, 2.0, False))


def render_va(c):
    t = open(os.path.join(HERE, "cva_cap.va.template")).read()
    for k, tag in (("Cmax", "@CMAX@"), ("Cmin", "@CMIN@"), ("Vfb", "@VFB@"), ("Vslp", "@VSLP@")):
        t = t.replace(tag, f"{c[k]:.6g}")
    return t


def compile_va(va_path, osdi_path):
    subprocess.run([spice.OPENVAF, va_path, "-o", osdi_path], check=True, capture_output=True)


def subckt_text(c):
    return f"""* =====================================================================
* FGFET equivalent subcircuit - Fig. 1(c) of Kim et al., IEEE Access 2023
* Generated by scripts/fit_cva.py
*
* Terminals
*   WL : word line   (VFET gate, top plate of C_VA)
*   DL : data line   (VFET drain)
*   SL : sense line  (SFET drain)
*   SS : SFET source (GND or the logic pull-down stack)
*   B  : substrate   (GND)
* Parameters
*   w_dev      : device width (VFET = SFET = C_VA width)
*   delvto_val : SFET threshold shift; 0 for A/C-type, 0.9 for B-type adders
*
* Usage (ngspice >= 39 with OSDI):
*   .control
*   pre_osdi <path>/cva_cap.osdi
*   .endc
*   .include <path>/fgfet_subckt.sp
*   X1 wl dl sl 0 0 FGFET w_dev=64n
*
* IMPORTANT: use `.options gmin=1e-15 chgtol=1e-18` (or tighter).
*  - ngspice's default gmin = 1e-12 S sits across the VFET source junction on
*    the floating memory node and discharges it within microseconds.
*  - the default chgtol = 1e-14 C exceeds the ~fC node charge, so the floating
*    node drifts by ~30 uV per WL cycle from integration error alone.
* =====================================================================
.include sfet_32nm.pm
.include vfet_32nm.pm

.model cva_fgfet cva_cap Cmax={c['Cmax']:.6g} Cmin={c['Cmin']:.6g} Vfb={c['Vfb']:.6g} Vslp={c['Vslp']:.6g}

.subckt FGFET WL DL SL SS B params: w_dev=64n delvto_val=0
* 1. vertical access FET: drain = DL, gate = WL, source = memory node MN
M_VFET DL WL MN B vfet_nmos L=100.2n W={{w_dev}}
* 2. sense FET: drain = SL, gate = MN, source = SS
M_SFET SL MN SS B sfet_nmos L=32n W={{w_dev}} delvto={{delvto_val}}
* 3. voltage-dependent WL-MN coupling capacitor (Verilog-A, width in um)
N_CVA WL MN cva_fgfet W={{w_dev/1u}}
* 4. 1000 TOhm DC path so the floating node has a defined operating point
R_conv MN 0 1000T
.ends FGFET
"""


def fig4_netlist(osdi, subckt, vdl_list, w_dev="1u", tstep="2n"):
    """Table II sequence: initialize (WL=3), write (WL=3, DL=data), storage (WL=-2), read (WL=0.5, SL=0.9)."""
    e = EDGE
    wl = (f"pwl(0 0 {e} 0 {2*e} 3 {T_STORE} 3 {T_STORE+e} -2 {T_READ} -2 {T_READ+e} 0.5 {T_END} 0.5)")
    sl = f"pwl(0 0 {T_READ} 0 {T_READ+e} 0.9 {T_END} 0.9)"
    lines = [f"* Fig. 4 transient", f".include {subckt}", f"VWL wl 0 {wl}", f"VSL sl 0 {sl}"]
    for i, vdl in enumerate(vdl_list):
        dl = f"pwl(0 0 {T_WRITE} 0 {T_WRITE+e} {vdl} {T_STORE} {vdl} {T_STORE+e} 0 {T_END} 0)"
        lines += [f"VDL{i} dl{i} 0 {dl}", f"X{i} wl dl{i} sl 0 0 FGFET w_dev={w_dev}"]
    vecs = " ".join(f"v(x{i}.mn)" for i in range(len(vdl_list)))
    lines += [f".options method=gear reltol=1e-4 {SIM_OPTS}", ".control", f"pre_osdi {osdi}",
              f"tran {tstep} {T_END}", "set wr_singlescale", f"wrdata vmn.txt {vecs}",
              "quit", ".endc", ".end"]
    return "\n".join(lines) + "\n"


class CvaFit:
    def __init__(self):
        self.work = tempfile.mkdtemp(prefix="cva_")
        self.va = os.path.join(self.work, "cva_cap.va")
        self.osdi = os.path.join(self.work, "cva_cap.osdi")
        open(self.va, "w").write(render_va(CVA0))
        compile_va(self.va, self.osdi)
        for f in ("sfet_32nm.pm", "vfet_32nm.pm"):
            os.symlink(os.path.join(MODELS, f), os.path.join(self.work, f))
        self.keys = list(BOUNDS)

    def to_c(self, u):
        c = {}
        for k, ui in zip(self.keys, u):
            lo, hi, lg = BOUNDS[k]
            c[k] = lo * (hi / lo) ** ui if lg else lo + ui * (hi - lo)
        return c

    def to_u(self, c):
        u = []
        for k in self.keys:
            lo, hi, lg = BOUNDS[k]
            u.append(np.log(c[k] / lo) / np.log(hi / lo) if lg else (c[k] - lo) / (hi - lo))
        return np.array(u)

    def simulate(self, c):
        sub = os.path.join(self.work, "fgfet_subckt.sp")
        open(sub, "w").write(subckt_text(c))
        out = spice.run(fig4_netlist(self.osdi, sub, list(TARGETS)), ["vmn.txt"])
        d = spice.load_cols(out["vmn.txt"])
        return d[:, 0], {vdl: d[:, 1 + i] for i, vdl in enumerate(TARGETS)}

    def residual(self, u):
        t, v = self.simulate(self.to_c(u))
        return np.concatenate([[w * (np.interp(tt, t, v[vdl]) - vt) for tt, vt, w in pts]
                               for vdl, pts in TARGETS.items()])


def main():
    f = CvaFit()
    u0 = f.to_u(CVA0)
    r0 = f.residual(u0)
    sol = least_squares(f.residual, u0, bounds=(0, 1), diff_step=1e-3)
    c = f.to_c(sol.x)
    print(f"C_VA fit: weighted rms {np.sqrt(np.mean(r0**2)):.4f} -> {np.sqrt(np.mean(sol.fun**2)):.4f} V")
    for k in f.keys:
        print(f"    {k:5s} = {c[k]:.5g}")
    t, v = f.simulate(c)
    for vdl, pts in TARGETS.items():
        print(f"  V_DL = {vdl} V")
        for tt, vt, _ in pts:
            print(f"    t = {tt*1e6:5.3f} us  target {vt:+.3f}  model {np.interp(tt, t, v[vdl]):+.3f}")

    open(VA_OUT, "w").write(render_va(c))
    compile_va(VA_OUT, OSDI_OUT)
    open(SUBCKT_OUT, "w").write(subckt_text(c))
    print("wrote cva_cap.va, cva_cap.osdi, fgfet_subckt.sp")


if __name__ == "__main__":
    main()
