#!/usr/bin/env python3
"""Stage 2.2: calibrate the SFET (= baseline 32 nm NMOS) BSIM4 card.

Starts from the PTM 32 nm HP `nmos` card and fits it to the digitized TCAD
data of Fig. 2(a) (Id-Vg @ Vds = 0.05 V, 1 V) and Fig. 2(c) (Cgg-Vg).

Writes ../models/sfet_32nm.pm (model `sfet_nmos`) and ../models/cmos_32nm.pm (`nmos_32nm`,
identical to the SFET as stated in Sec. III-A, plus the PTM `pmos_32nm`).
"""
import os

from bsim4_card import parse_card, write_card
from fitlib import CardFitter, TiedFitter, cv_residual, iv_residual

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
DATA = os.path.join(ROOT, "data")
MODELS = os.path.join(ROOT, "models")
PTM = os.path.join(MODELS, "ptm_32nm_hp_base.pm")
W, L = "1u", "32n"           # Fig. 2 is normalised per um of width

# Table I gate stack: 0.7 nm SiO2 + 3 nm HfO2 (k ~ 22)
EOT = 0.7e-9 + 3.0e-9 * 3.9 / 22.0          # = 1.23 nm

FIXED = {
    "toxe": EOT, "toxm": EOT, "toxref": EOT, "toxp": EOT - 0.25e-9, "epsrox": 3.9,
    # The 3.7 nm physical high-k stack makes direct gate tunnelling negligible.
    # BSIM4 would compute it from the 1.23 nm EOT and slowly bleed the floating
    # memory node, so gate-current models are switched off.
    "igcmod": 0, "igbmod": 0,
}

# GIDL is invisible in Fig. 2 (Vgs >= 0) but dominates once the memory node is
# driven negative (storage / read of '0'): PTM values give ~1 uA/um at Vdg = 1.5 V.
# The paper credits the FGFET's Si3N4 barrier with suppressing GIDL (Sec. III-B)
# and states that a stored '0' conducts no read current, so the SFET has GIDL
# off. The baseline CMOS card keeps the PTM GIDL.
SFET_ONLY = {"agidl": 0.0}


IV_FREE = [  # (name, lo, hi, log)
    ("vth0", 0.25, 0.65, False),
    ("voff", -0.30, 0.05, False),
    ("nfactor", 0.5, 4.0, False),
    ("eta0", 1e-4, 0.2, True),
    ("u0", 0.01, 0.15, True),
    ("ua", -1e-9, 3e-9, False),
    ("vsat", 5e4, 5e5, True),
    ("rdsw", 20.0, 600.0, True),
    ("pclm", 0.005, 1.0, True),
]

CV_FREE = [
    ("dlc", -60e-9, 5e-9, False),     # C-V channel-length offset (Leff_cv = L + XL - 2 DLC)
    ("cgso", 1e-12, 4e-10, True),     # cgdo tied to cgso (symmetric device)
    ("cf", 1e-12, 2e-10, True),       # outer fringing (BSIM4 default ~1.3e-10 F/m is too high)
    ("cgsl", 1e-13, 8e-10, True),     # cgdl tied to cgsl
    ("voffcv", -0.3, 0.3, False),
    ("noff", 0.5, 3.5, False),
    ("acde", 0.3, 3.0, False),
]


def main():
    dtype, base = parse_card(PTM, "nmos")
    p = dict(base)
    p.update(FIXED)
    p["dlc"] = p["lint"]
    p["cf"] = 1.0e-10

    print("SFET: fitting Id-Vg (Fig. 2a)")
    p = CardFitter("fitdev", dtype, p, IV_FREE, iv_residual(DATA, "sfet", W, L)).fit(max_nfev=400)
    print("SFET: fitting Cgg-Vg (Fig. 2c)")
    p = TiedFitter("fitdev", dtype, p, CV_FREE, cv_residual(DATA, "sfet", W, L)).fit(max_nfev=300)
    p["cgdo"], p["cgdl"] = p["cgso"], p["cgsl"]

    note = ("SFET of the FGFET (Kim et al., IEEE Access 2023), 32 nm planar HKMG NMOS.\n"
            "Generated by scripts/fit_sfet.py from PTM 32nm HP + fit to Fig. 2(a),(c) TCAD data.\n"
            f"EOT = 0.7 nm SiO2 + 3 nm HfO2 -> toxe = {EOT*1e9:.3f} nm; igcmod = igbmod = 0.\n"
            "Use W/L = 1u/32n to reproduce the per-um curves of Fig. 2.")
    sfet = dict(p, **SFET_ONLY)
    note += "\nGIDL disabled (agidl = 0): Si3N4-barrier GIDL suppression, Sec. III-B."
    write_card(os.path.join(MODELS, "sfet_32nm.pm"), [("sfet_nmos", dtype, sfet, note)],
               header="FGFET sense transistor (SFET) - BSIM4 (level 54)")

    pdtype, pbase = parse_card(PTM, "pmos")
    write_card(os.path.join(MODELS, "cmos_32nm.pm"), [
        ("nmos_32nm", dtype, p, "Baseline 32 nm NMOS: same fit as sfet_nmos (Sec. III-A), with PTM GIDL kept."),
        ("pmos_32nm", pdtype, pbase, "Baseline 32 nm PMOS: PTM 32nm HP pmos, unmodified\n"
                                     "(the paper gives no PMOS TCAD data to calibrate against)."),
    ], header="Baseline 32 nm CMOS for the full-adder benchmarks (VDD = 0.9 V)")
    print("wrote sfet_32nm.pm, cmos_32nm.pm")


if __name__ == "__main__":
    main()
