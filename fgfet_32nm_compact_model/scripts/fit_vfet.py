#!/usr/bin/env python3
"""Stage 2.3: calibrate the VFET (vertical access transistor) BSIM4 card.

Structure from Table I: L_CH = 100.2 nm, T_OX = 10 nm SiO2, intrinsic channel,
2e20 cm^-3 S/D, metal gate, 2 nm Si3N4 S/D tunnel barriers. The barriers are
not a BSIM4 feature; their effect (sub-nA/um on-current, no GIDL) is absorbed
into a low mobility / large series resistance, as the guide suggests.

Fit targets: digitized TCAD data of Fig. 2(b) (Id-Vg @ Vds = 0.05 V, 1 V) and
Fig. 2(d) (Cgg-Vg). Note the VFET on-current in Fig. 2(b) is ~2e-9 A/um at
Vds = 0.05 V and ~2e-8 A/um at Vds = 1 V (the y axes run 1e-12..1e-8 A/um).

Writes ../models/vfet_32nm.pm (model `vfet_nmos`).
"""
import os

from bsim4_card import parse_card, write_card
from fitlib import CardFitter, TiedFitter, cv_residual, iv_residual

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
DATA = os.path.join(ROOT, "data")
MODELS = os.path.join(ROOT, "models")
PTM = os.path.join(MODELS, "ptm_32nm_hp_base.pm")
W, L = "1u", "100.2n"

TOX = 10e-9
FIXED = {
    # gate stack / geometry (Table I)
    "toxe": TOX, "toxp": TOX, "toxm": TOX, "toxref": TOX, "dtox": 0.0, "epsrox": 3.9,
    "xl": 0.0, "lint": 0.0, "wint": 0.0, "dwc": 0.0,
    "ndep": 1e15,           # intrinsic pillar channel
    "nsd": 2e20, "xj": 25e-9,
    "k1": 0.01, "k2": 0.0,  # thin undoped pillar: practically no body effect
    # Si3N4 barriers suppress GIDL; thick SiO2 -> no gate tunnelling
    "igcmod": 0, "igbmod": 0, "agidl": 0.0, "bgidl": 2.3e9, "cgidl": 0.5,
    # the pillar sits on the SFET gate, there is no S/D junction to a substrate
    "jss": 0.0, "jsws": 0.0, "jswgs": 0.0, "jsd": 0.0, "jswd": 0.0, "jswgd": 0.0,
    "cjs": 0.0, "cjsws": 0.0, "cjswgs": 0.0, "cjd": 0.0, "cjswd": 0.0, "cjswgd": 0.0,
    "rbodymod": 0, "rgatemod": 0,
    # Wrap-gate 100 nm pillar: no Vth roll-off. With an intrinsic channel BSIM4's Xdep
    # is ~1 um, so the PTM dsub = 0.1 would multiply eta0 by ~300 (runaway DIBL);
    # dsub = 1 keeps the DIBL factor O(1) so eta0 alone sets it.
    "dvt0": 0.0, "dvtp0": 0.0, "dsub": 1.0,
    # capmod = 2 adds bulk-MOSFET charge-centroid / surface-potential (DeltaPhi)
    # corrections that assume a doped body; with the undoped pillar's k1 ~ 0 the
    # DeltaPhi term blows up and distorts the moderate-inversion C-V (Fig. 2d fit
    # stuck at ~5.8 % rms). capmod = 1 keeps the noff/voffcv weak-inversion form
    # without those corrections.
    "capmod": 1,
}

IV_FREE = [
    ("vth0", 0.4, 1.6, False),
    ("voff", -0.3, 0.1, False),
    ("cit", -2.5e-3, 5e-3, False),   # cit < 0 gives n < 1: the sub-60 mV/dec onset of Fig. 2(b)
    ("eta0", 1e-4, 0.5, True),
    ("u0", 1e-6, 0.05, True),
    ("ua", -1e-9, 1e-8, False),
    ("vsat", 1e2, 2e5, True),
    ("rdsw", 1e3, 1e9, True),
    ("prwg", 0.0, 5.0, False),
    ("pclm", 0.005, 5.0, True),
]

CV_FREE = [
    ("dlc", -30e-9, 30e-9, False),
    ("cgso", 1e-12, 3e-10, True),
    ("cf", 1e-12, 2e-10, True),
    ("cgsl", 1e-13, 3e-10, True),
    ("ckappas", 0.02, 3.0, True),     # ckappad tied
    ("voffcv", -0.5, 0.5, False),
    # noff * n ~ 3.4-3.9 from the exponential C-V onset of Fig. 2(d) (0.70-0.95 V)
    ("noff", 0.3, 4.0, False),
    # phin lowers VFBzb = vth0 - phis - k1*sqrt(phis): the floating, undoped pillar
    # cannot accumulate, so Cgg must stay at the overlap level below threshold.
    ("phin", 0.0, 2.0, False),
]


def main():
    dtype, base = parse_card(PTM, "nmos")
    p = dict(base)
    p.update(FIXED)
    p.update({"vth0": 0.75, "voff": -0.1, "cit": 0.0, "eta0": 0.01, "u0": 1e-3, "ua": 0.0,
              "vsat": 1e4, "rdsw": 1e6, "prwg": 0.0, "pclm": 0.1, "dlc": 0.0, "cf": 5e-11,
              "phin": 0.6})

    # phin (C-V stage) feeds back weakly into I-V, so alternate the two stages
    for rnd in (1, 2):
        print(f"VFET round {rnd}: fitting Id-Vg (Fig. 2b)")
        p = CardFitter("fitdev", dtype, p, IV_FREE, iv_residual(DATA, "vfet", W, L, floor=1e-16)).fit(max_nfev=600)
        print(f"VFET round {rnd}: fitting Cgg-Vg (Fig. 2d)")
        p = TiedFitter("fitdev", dtype, p, CV_FREE, cv_residual(DATA, "vfet", W, L)).fit(max_nfev=400)
    p["cgdo"], p["cgdl"], p["ckappad"] = p["cgso"], p["cgsl"], p["ckappas"]

    note = ("VFET of the FGFET (Kim et al., IEEE Access 2023): vertical pillar access transistor.\n"
            "Generated by scripts/fit_vfet.py from PTM 32nm HP + Table I geometry + fit to Fig. 2(b),(d).\n"
            "Use L = 100.2n; W/L = 1u/100.2n reproduces the per-um curves of Fig. 2.\n"
            "Si3N4 S/D barrier transport is lumped into u0 / rdsw / vsat; junctions and GIDL disabled.")
    write_card(os.path.join(MODELS, "vfet_32nm.pm"), [("vfet_nmos", dtype, p, note)],
               header="FGFET vertical access transistor (VFET) - BSIM4 (level 54)")
    print("wrote vfet_32nm.pm")


if __name__ == "__main__":
    main()
